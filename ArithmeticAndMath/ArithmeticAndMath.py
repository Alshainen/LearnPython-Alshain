import math
#Untuk kebutuhan nilai pi, e, dan lainnya

# ARITHMETIC
student = 64

print(student + 50) # Penjumlahan
print(student - 400) # Pengurangan
print(student * 3) #Perkalian
print(student / 5) #Pembagian
print(student ** 2) #Pangkat
print(student % 5) #Modulus / Sisa bagi


# MATH
nilai1 = 10.5
nilai2 = 10.51
nilai3 = 4
nilai4 = 5
nilai5 = -3
nilai6 = 16

print(round(nilai1), round(nilai2)) #Bulatkan ke nilai terdekat
print(abs(nilai5)) #Ubah nilai negatif menjadi positif
print(pow(nilai3, nilai4)) #Pangkat (berapa kah nilai3 pangkat nilai4)
print(max(nilai1, nilai2, nilai3)) #Mencari nilai terbesar di antara nilai lainnya
print(min(nilai1, nilai2, nilai3)) #Mencari nilai terkecil di antara nilai lainnya

# Dari Import Math di atas:
print(math.pi) #Menampilkan nilai pi
print(math.e) #Menampilkan nilai e
print(math.sqrt(nilai6)) #Akar kuadrat
print(math.ceil(nilai1)) #Membulatkan bilangan ke atas
print(math.floor(nilai2)) #Membulatkan bilangan ke bawah